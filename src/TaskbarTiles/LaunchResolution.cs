// Launch identity is evidence, not a title/name heuristic. Shell-generated grouping
// keys are not explicit per-window AppUserModelIDs. All lookups remain local.
using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Runtime.InteropServices;
using System.Security.Cryptography;
using System.Text;
